package com.example.model;

import java.time.LocalDate;
import java.time.LocalDateTime;

public record AISummary(Integer summaryId, int generatedBy, String summaryContent, int reportCount,
                        LocalDate summaryPeriodStart, LocalDate summaryPeriodEnd,
                        LocalDateTime generatedAt) {

    public AISummary {
        Validation.requirePositive(generatedBy, "Generated by");
        summaryContent = Validation.requireText(summaryContent, "Summary content", 20000);
        if (reportCount < 0) {
            throw new IllegalArgumentException("Report count cannot be negative.");
        }
        Validation.requireNonNull(summaryPeriodStart, "Period start");
        Validation.requireNonNull(summaryPeriodEnd, "Period end");
        if (summaryPeriodEnd.isBefore(summaryPeriodStart)) {
            throw new IllegalArgumentException("Period end cannot be before period start.");
        }
        Validation.requireNonNull(generatedAt, "Generated at");
    }
}
